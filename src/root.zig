test "pinned version metadata" {
    try std.testing.expectEqualStrings("3.53.4", build_profile.sqlite_version);
    try std.testing.expectEqual(@as(c_int, 3_053_004), build_profile.sqlite_version_number);
    try std.testing.expectEqual(@as(c_int, 1), build_profile.threadsafe);
}

test "result codes preserve extended values" {
    const extended = ResultCode.fromC(10 | (3 << 8));
    try std.testing.expectEqual(@as(c_int, 778), extended.toC());
    try std.testing.expectEqual(ResultCode.io_error, extended.primary());
}

